# Build long-format dataframe for ggplot
region_pairs_list <- list(
  list(r1="South Asian",  r2="West Asian",    label="South vs West Asian"),
  list(r1="South Asian",  r2="Central Asian", label="South vs Central Asian"),
  list(r1="West Asian",   r2="Central Asian", label="West vs Central Asian")
)

build_boxplot_df <- function(rp) {
  r1 <- rp$r1; r2 <- rp$r2; lab <- rp$label
  g1  <- rownames(gdist_mat)[sapply(rownames(gdist_mat), get_region) == r1]
  g2  <- rownames(gdist_mat)[sapply(rownames(gdist_mat), get_region) == r2]
  btwn <- as.vector(gdist_mat[g1, g2])
  w1   <- diag(gdist_mat)[g1]; w1 <- w1[w1 > 0]
  w2   <- diag(gdist_mat)[g2]; w2 <- w2[w2 > 0]
  rbind(
    data.frame(value=w1,   group=paste0("Within\n",r1),  comparison=lab, color=REGION_COLORS[r1]),
    data.frame(value=w2,   group=paste0("Within\n",r2),  comparison=lab, color=REGION_COLORS[r2]),
    data.frame(value=btwn, group="Between\nRegions",      comparison=lab, color="#FF9800")
  )
}

box_df <- do.call(rbind, lapply(region_pairs_list, build_boxplot_df))

# Compute medians for annotation
