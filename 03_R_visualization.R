make_focus_panel <- function(focus_groups, subtitle) {
  background <- mds_df
  foreground  <- mds_df %>% filter(GROUP %in% focus_groups)
  fg_centroids<- foreground %>%
    group_by(GROUP, REGION) %>%
    summarise(MDS1 = mean(MDS1), MDS2 = mean(MDS2), .groups = "drop")

  ggplot() +
    geom_point(data = background,  aes(x = MDS1, y = MDS2),
               color = "#CCCCCC", size = 1.0, alpha = 0.3) +
    geom_point(data = foreground,  aes(x = MDS1, y = MDS2, color = REGION),
               size = 2.0, alpha = 0.85) +
    geom_point(data = fg_centroids, aes(x = MDS1, y = MDS2, color = REGION),
               shape = 8, size = 6, stroke = 1.5) +
    geom_label_repel(
      data = fg_centroids,
      aes(x = MDS1, y = MDS2, label = GROUP, color = REGION),
      size = 3.5, fontface = "bold",
      fill = alpha("white", 0.8),
      box.padding = unit(0.3, "lines"),
      max.overlaps = 20,
      show.legend  = FALSE
    ) +
    scale_color_manual(values = REGION_COLORS, name = "Region") +
    labs(title = subtitle, x = "MDS Axis 1", y = "MDS Axis 2") +
    theme_bw(base_size = 12) +
    theme(
      plot.title       = element_text(face = "bold", size = 12),
      axis.title       = element_text(face = "bold"),
      panel.background = element_rect(fill = "#F8F9FA"),
      panel.grid.major = element_line(linetype = "dashed", color = "#DDDDDD"),
      panel.grid.minor = element_blank(),
      legend.position  = "bottom"
    )
}

