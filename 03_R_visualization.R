# Statistical Analysis: ANOVA and pairwise tests on IBS distances
cat("\n-- Statistical Tests: ANOVA and pairwise comparisons --\n")

sink(file.path(OUT_DIR, "Region_ANOVA_results.txt"))
cat("IBS distance comparisons by region\n\n")

# Build individual-level distance summary
# (using between-group level distances from the 24x24 matrix)
all_dist_df <- do.call(rbind, lapply(region_pairs_list, build_boxplot_df))

cat("-- One-way ANOVA: does region explain between-group IBS distance? --\n")
anova_model <- aov(value ~ group, data = all_dist_df)
print(summary(anova_model))

cat("\n-- Tukey HSD Post-hoc: pairwise regional comparisons --\n")
tukey_result <- TukeyHSD(anova_model)
print(tukey_result)

cat("\n-- Descriptive statistics by group --\n")
desc_stats <- all_dist_df %>%
  group_by(comparison, group) %>%
  summarise(
    N       = n(),
    Mean    = round(mean(value),   4),
    Median  = round(median(value), 4),
    SD      = round(sd(value),     4),
    Min     = round(min(value),    4),
    Max     = round(max(value),    4),
    .groups = "drop"
  )
print(as.data.frame(desc_stats), row.names = FALSE)

sink()
cat("  Saved: Region_ANOVA_results.txt\n")

# Summary table (CSV export)
