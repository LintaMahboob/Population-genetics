# Population to region mapping
SOUTH_ASIA   <- c("Indian","Pakistani","Afghani","Nepalease")
WEST_ASIA    <- c("Turkish","Iranian","Armenian","Lebanese","Cypriot",
                  "Israeli","Palestinian","Jordanian","Iraqi","Saudi",
                  "Syrian","Yemeni","Egypt","Azeri")
CENTRAL_ASIA <- c("Kazakh","Kyrgyz","Uzbeks","Turkmen","Tajik","Tajik_4M")

get_region <- function(group) {
  if (group %in% SOUTH_ASIA)    return("South Asian")
  if (group %in% WEST_ASIA)     return("West Asian")
  if (group %in% CENTRAL_ASIA)  return("Central Asian")
  return("Other")
}

