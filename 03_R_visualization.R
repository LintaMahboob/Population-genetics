groups_vec <- rownames(gdist_mat)
summary_rows <- lapply(groups_vec, function(grp) {
  region  <- get_region(grp)
  n       <- sum(meta$GROUP == grp)
  wd      <- gdist_mat[grp, grp]
  others  <- gdist_mat[grp, colnames(gdist_mat) != grp]
  md      <- mean(others)
  nearest <- names(which.min(others))
  nd      <- min(others)
  data.frame(
    Population           = grp,
    Region               = region,
    N                    = n,
    Within_group_IBS     = round(wd, 4),
    Mean_dist_to_others  = round(md, 4),
    Nearest_population   = nearest,
    Nearest_IBS_distance = round(nd, 4),
    stringsAsFactors     = FALSE
  )
})

summary_table <- do.call(rbind, summary_rows)
summary_table <- summary_table[order(summary_table$Region, summary_table$Population), ]

write.csv(summary_table,
          file.path(OUT_DIR, "Table1_stats.csv"),
          row.names = FALSE)
